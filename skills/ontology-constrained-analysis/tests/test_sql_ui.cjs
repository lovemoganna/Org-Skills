const assert = require('node:assert/strict');
const ui = require('../scripts/sql_ui.js');
const one = 'select uid,amount from fiat_transactions where amount>1 order by uid;';
const normalized = ui.formatSQL(one);
for (const clause of ['SELECT ', '\nFROM ', '\nWHERE ', '\nORDER BY ']) assert.ok(normalized.includes(clause), clause);
assert.ok(!normalized.includes('<span'));
assert.ok(ui.highlightSQL(normalized).includes('sql-keyword'));
const read = "SELECT * FROM read_xlsx('https://docs.google.com/x?query=AND FROM', sheet = 'users', header = true)";
const shown = ui.formatSQL(read);
assert.ok(shown.includes("'https://docs.google.com/x?query=AND FROM'"));
assert.ok(shown.includes('\n  sheet ='));
assert.ok(shown.includes('\n  header ='));
const cte = 'WITH a AS (SELECT x,y FROM t WHERE x>0) SELECT x, SUM(y) AS s FROM a GROUP BY x ORDER BY s DESC;';
const cteShown = ui.formatSQL(cte);
assert.ok(cteShown.includes('WITH a AS ('));
assert.ok(cteShown.includes('\nGROUP BY '));
assert.ok(cteShown.includes('\nORDER BY '));
const comments = "SELECT 'FROM should not split' AS x -- WHERE not SQL\nFROM t;";
assert.ok(ui.formatSQL(comments).includes("'FROM should not split'"));
assert.ok(ui.formatSQL(comments).includes('-- WHERE not SQL'));
const markup = ui.highlightSQL("SELECT '<script>alert(1)</script>' AS x;");
assert.ok(markup.includes('&lt;script&gt;') && !markup.includes('<script>'));
console.log('PASS six source SQL-format/hilite regression assertions; content is not query execution.');
